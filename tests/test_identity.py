"""The old identity is gone from the tree. PENDING lists what later stages still have to rewrite: shrink it, never grow it."""
import re
import subprocess
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OLD_NAMES = ["d" + "bs", "po" + "sb", "digi" + "bank", "ten" + "cent", "hun" + "yuan", "oc" + "bc", "sing" + "tel", "scam" + "shield"]     # split, so this list is no hit itself
TERMS = re.compile(r"\b(?:" + "|".join(OLD_NAMES) + r")\b|\bgiro\b|\bcpf\b|mdm chen|\bS\$\d|\bSGD\b", re.I)
PENDING = set()
ALLOWED = {"tests/test_identity.py", "app/agent/request_guard.py"}     # this list itself; a refusal that names other currencies
SKIP_SUFFIX = {".png", ".jpg", ".jpeg", ".pdf", ".wav", ".webm"}


class TestIdentity(unittest.TestCase):
    def test_no_old_identity_terms(self):
        files = subprocess.check_output(["git", "ls-files", "--cached", "--others", "--exclude-standard"], cwd=ROOT, text=True).split("\n")
        hits = []
        for name in files:
            path = ROOT / name
            if not name or name in PENDING or name in ALLOWED or path.suffix in SKIP_SUFFIX or not path.is_file() or "vendor/" in name:
                continue
            try:
                for i, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
                    if TERMS.search(line):
                        hits.append(f"{name}:{i}: {line.strip()[:90]}")
            except UnicodeDecodeError:
                continue
        self.assertEqual(hits, [])

    def test_old_assets_are_gone(self):
        for path in ("web/" + "d" + "bs-logo.svg", "app/bank", "qa/REPORT.md", "docs/images/banner.jpg"):
            self.assertFalse((ROOT / path).exists(), path)
        # Generated by eval/run_eval.py, so it may exist locally, but it isn't source.
        tracked = subprocess.check_output(["git", "ls-files", "eval/contract-report.json"], cwd=ROOT, text=True)
        self.assertEqual(tracked.strip(), "")
